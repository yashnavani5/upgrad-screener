// Generate web/lib/contracts/*.ts from ../contracts/*.json (written by `uv run screener export-schema`).
// One module per view (names like `Rank` differ between views, so they must not be merged), plus an index
// that re-exports each view's row type and its nested reference types.
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const here = path.dirname(fileURLToPath(import.meta.url));
const contractsDir = path.resolve(here, "..", "..", "contracts");
const outDir = path.resolve(here, "..", "lib", "contracts");
const banner =
  "// GENERATED by `npm run gen:types` from ../contracts/*.json. Do not edit.\n" +
  "// Source of truth: src/screener/contracts.py (Pydantic) -> `uv run screener export-schema`.\n";

await rm(outDir, { recursive: true, force: true });
await mkdir(outDir, { recursive: true });
const files = (await readdir(contractsDir)).filter((f) => f.endsWith(".json")).sort();
const index = [banner];
for (const file of files) {
  const schema = JSON.parse(await readFile(path.join(contractsDir, file), "utf8"));
  const ts = await compile(schema, schema.title, { bannerComment: "", additionalProperties: false, format: false });
  const mod = file.replace(/\.json$/, "");
  await writeFile(path.join(outDir, `${mod}.ts`), banner + "\n" + ts, "utf8");
  const interfaces = [...ts.matchAll(/^export interface (\w+)/gm)].map((m) => m[1]);
  // Row type plus nested reference interfaces (FounderRef, EvidenceRef, ...), skipping numbered duplicates.
  const exported = interfaces.filter((n) => !/\d$/.test(n) && (n === schema.title || /(Ref|Detail|Component|Counts|Usage|Snapshot)$/.test(n)));
  index.push(`export type { ${exported.join(", ")} } from "./${mod}";`);
}
const seen = new Set();
const lines = index.map((l) => {
  if (!l.startsWith("export type {")) return l;
  const names = l.slice(l.indexOf("{") + 1, l.indexOf("}")).split(",").map((s) => s.trim()).filter((n) => n && !seen.has(n));
  names.forEach((n) => seen.add(n));
  return names.length ? `export type { ${names.join(", ")} } from ${l.slice(l.indexOf("from ") + 5)}` : "";
});
await writeFile(path.join(outDir, "index.ts"), lines.filter(Boolean).join("\n") + "\n", "utf8");
console.log(`wrote lib/contracts/ (${files.length} views)`);
